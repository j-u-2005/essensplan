CREATE TABLE IF NOT EXISTS recipes (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  url TEXT NOT NULL UNIQUE,
  source TEXT NOT NULL,
  title TEXT NOT NULL,
  image TEXT,
  servings INTEGER NOT NULL DEFAULT 4,
  minutes INTEGER NOT NULL DEFAULT 45,
  effort INTEGER NOT NULL DEFAULT 20,
  ingredients TEXT NOT NULL DEFAULT '[]',
  s_breakfast INTEGER NOT NULL DEFAULT 0,
  s_lunch INTEGER NOT NULL DEFAULT 0,
  s_snack INTEGER NOT NULL DEFAULT 0,
  s_dinner INTEGER NOT NULL DEFAULT 0,
  cold_ok INTEGER NOT NULL DEFAULT 0,
  micro_ok INTEGER NOT NULL DEFAULT 1,
  shelf_days INTEGER NOT NULL DEFAULT 3,
  batch_ok INTEGER NOT NULL DEFAULT 0,
  sweet INTEGER NOT NULL DEFAULT 0,
  oats INTEGER NOT NULL DEFAULT 0,
  fructose INTEGER NOT NULL DEFAULT 0,
  cost INTEGER NOT NULL DEFAULT 1,
  protein TEXT NOT NULL DEFAULT 'veg',
  dtype TEXT NOT NULL DEFAULT 'sonstiges',
  leftover_ok INTEGER NOT NULL DEFAULT 0,
  raw_ctx INTEGER NOT NULL DEFAULT 0,
  blocked INTEGER NOT NULL DEFAULT 0,
  blocked_reason TEXT,
  rating INTEGER NOT NULL DEFAULT 0,
  imported_at TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_recipes_pool ON recipes (blocked, rating);
CREATE INDEX IF NOT EXISTS idx_recipes_source ON recipes (source);

CREATE TABLE IF NOT EXISTS crawl (
  url TEXT PRIMARY KEY,
  source TEXT NOT NULL,
  status TEXT NOT NULL,
  fetched_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_crawl_source ON crawl (source);

CREATE TABLE IF NOT EXISTS plans (
  week_start TEXT PRIMARY KEY,
  created_at TEXT NOT NULL,
  seed INTEGER NOT NULL DEFAULT 0,
  params TEXT NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS plan_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  week_start TEXT NOT NULL,
  day INTEGER NOT NULL,
  slot TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'recipe',
  recipe_id INTEGER,
  title TEXT,
  servings INTEGER NOT NULL DEFAULT 1,
  note TEXT,
  leftover INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_items_week ON plan_items (week_start);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
